// The real /api/admin/reports route with the Housecall Pro reader swapped for a fake.
const esbuild = require("esbuild");
const path = require("path");
const fs = require("fs");
const SRC = path.join(__dirname, "../../src");
const NEXT = path.join(__dirname, "../../node_modules/next/server.js");
const TMP = path.join(__dirname, "..", ".tmp");
fs.mkdirSync(TMP, { recursive: true });
let passes = 0, failures = 0;
const check = (name, ok, detail = "") => { if (ok) passes++; else { failures++; console.log(`FAIL ${name}${detail ? "  <- " + detail : ""}`); } };
process.env.ADMIN_PASSWORD = "pw-for-tests";
(async () => {
  const fakeLive = path.join(TMP, "fake-reports-live.cjs");
  fs.writeFileSync(fakeLive, `module.exports.getLiveReport = async (range, fresh) => { globalThis.__CALLS.push([range, fresh]); if (globalThis.__FAIL) throw new Error(globalThis.__FAIL); return { range: { label: range } }; };`);
  const entry = path.join(TMP, "entry-reports.ts");
  fs.writeFileSync(entry, `export * as route from "@/app/api/admin/reports/route"; export { createSessionValue, ADMIN_COOKIE } from "@/lib/admin-session";`);
  const swap = { name: "swap", setup(b) { b.onResolve({ filter: /^@\/lib\/reports-live$/ }, () => ({ path: fakeLive })); } };
  const out = await esbuild.build({ entryPoints: [entry], bundle: true, write: false, format: "cjs", platform: "node", alias: { "@": SRC }, external: ["next/server", "node:crypto"], plugins: [swap], logLevel: "silent" });
  const mod = { exports: {} }; new Function("module", "exports", "require", out.outputFiles[0].text)(mod, mod.exports, (id) => require(id === "next/server" ? NEXT : id));
  const { route, createSessionValue, ADMIN_COOKIE } = mod.exports;
  const { NextRequest } = require(NEXT);
  const cookie = `${ADMIN_COOKIE}=${createSessionValue("pw-for-tests")}`;
  const get = async (qs, signed = true) => { const r = await route.GET(new NextRequest(`http://localhost:3000/api/admin/reports${qs}`, { headers: signed ? { cookie } : {} })); return { status: r.status, body: await r.json() }; };
  globalThis.__CALLS = [];
  check("T1 not signed in as admin: 401, Housecall Pro never asked", (await get("?range=30", false)).status === 401 && globalThis.__CALLS.length === 0);
  let r = await get("");
  check("T2 default range is 30 days", r.status === 200 && r.body.ok && JSON.stringify(globalThis.__CALLS.at(-1)) === JSON.stringify(["30", false]));
  for (const k of ["7", "90", "ytd", "last-month"]) check(`T3 range ${k} accepted`, (await get(`?range=${k}`)).status === 200);
  check("T4 fresh=1 skips the cache", (await get("?range=ytd&fresh=1")).status === 200 && JSON.stringify(globalThis.__CALLS.at(-1)) === JSON.stringify(["ytd", true]));
  check("T5 an unknown range is refused", (await get("?range=forever")).status === 400);
  globalThis.__FAIL = "HCP_API_KEY is not set";
  r = await get("?range=30");
  check("T6 not connected: says so", r.status === 502 && /not connected/.test(r.body.error), JSON.stringify(r.body));
  globalThis.__FAIL = "fetch failed: Zelda Quimby secret";
  r = await get("?range=30");
  check("T7 other failures: a safe category, never the raw error", r.status === 502 && /Could not read Housecall Pro/.test(r.body.error) && !/Zelda/.test(r.body.error), JSON.stringify(r.body));
  console.log(`\n${passes} passed, ${failures} failed`);
  process.exit(failures ? 1 : 0);
})().catch((e) => { console.error("TEST CRASH:", e); process.exit(2); });
